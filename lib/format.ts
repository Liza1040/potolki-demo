/**
 * Форматирование чисел с единицами. Одно место на весь набор.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ. Неразрывный пробел в исходнике визуально не
 * отличается от обычного, поэтому «7 020 ₽» с обычным пробелом читается
 * в коде как правильное — и молча рвётся переносом в узкой колонке.
 * Такой баг уже был: в formatRub перед знаком рубля стоял обычный пробел,
 * и на карточке пакета «24 900» уезжало на строку выше, а «₽» оставалось
 * внизу одно.
 *
 * Правило: символ неразрывного пробела существует РОВНО ЗДЕСЬ, один раз,
 * и задан кодом. Ни в одном другом файле его быть не должно — ни символом,
 * ни россыпью String.fromCharCode.
 */

/** Неразрывный пробел. Кодом, а не символом: символ в коде не виден. */
export const NBSP = String.fromCharCode(0xa0);

/** 7020 → «7 020»: разряды разделены неразрывным пробелом. */
export function formatNumber(value: number): string {
  return value.toLocaleString("ru-RU").replace(/\s/g, NBSP);
}

/**
 * Число с единицей одним неразрывным куском: «18 м²», «7 020 ₽», «40 мин».
 * Значение принимает и строкой — для уже готовых диапазонов вроде «3–4».
 */
export function withUnit(value: number | string, unit: string): string {
  const formatted = typeof value === "number" ? formatNumber(value) : value;
  return `${formatted}${NBSP}${unit}`;
}

/** 7020 → «7 020 ₽». Частый случай, поэтому отдельным именем. */
export function formatRub(value: number): string {
  return withUnit(value, "₽");
}
